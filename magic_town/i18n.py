def tr(lang: str, key: str, **kwargs) -> str:
    bucket = STRINGS.get(lang) or STRINGS["en"]
    text = bucket.get(key) or STRINGS["en"].get(key) or key
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except (KeyError, ValueError):
        return text


def error_text(lang: str, code: str | None) -> str:
    return tr(lang, f"err_{code or 'unexpected'}")
